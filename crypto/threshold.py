"""
(t, n) threshold ElGamal used as a key-encapsulation mechanism, over P-256.

This is the "threshold cryptosystem" of Desmedt and Frankel applied to ElGamal:
the secret key x is shared with Shamir's scheme (it IS Shamir underneath), but x is
never reconstructed. To open one ciphertext (R = r*G), each committee member i
publishes only a partial decryption D_i = f(i)*R, and any t of them combine to
S = x*R -- the same value the sender computed as r*Y -- through Lagrange
interpolation "in the exponent". The partials are useless for any other ciphertext,
so every single use of the key needs the quorum again.

    key generation   x random, Y = x*G, shares f(1..n) of a degree t-1 polynomial, f(0) = x
    encapsulate      r random, R = r*G, key = H(R, r*Y, context)
    partial decrypt  D_i = f(i)*R                        (member i, alone)
    combine          S = sum_i lambda_i * D_i = x*R      (anyone, with t partials)

Each partial can carry a Chaum-Pedersen proof that log_G(V_i) = log_R(D_i), where
V_i = f(i)*G is public, so a member that answers with garbage is identified.

Prototype simplifications (see docs/roteiro-cap4.md): the key is generated by a
trusted dealer (`deal`) instead of a distributed key generation, and ciphertexts are
not publicly verifiable (TDH2), so members must fetch R from the database themselves
rather than accept it from the requester.
"""
import hashlib
import secrets
from dataclasses import dataclass

from crypto import p256
from crypto.p256 import ORDER, G, Point


@dataclass(frozen=True)
class KeyShare:
    """Member `index`'s share f(index) of the secret key. Never leaves the member."""
    index: int
    value: int


@dataclass(frozen=True)
class PublicKey:
    point: Point  # Y = x*G
    threshold: int
    verification_points: dict  # {index: f(index)*G}, public


@dataclass(frozen=True)
class PartialDecryption:
    index: int
    point: Point  # D_i = f(i)*R


@dataclass(frozen=True)
class ShareProof:
    challenge: int
    response: int


def _random_scalar() -> int:
    return secrets.randbelow(ORDER - 1) + 1


def _lagrange_at_zero(index: int, indexes: list[int]) -> int:
    """lambda_j = prod_{m != j} m / (m - j) mod ORDER (Eq. 2.2 of the report)."""
    numerator = denominator = 1
    for other in indexes:
        if other != index:
            numerator = numerator * other % ORDER
            denominator = denominator * (other - index) % ORDER
    return numerator * pow(denominator, -1, ORDER) % ORDER


def _kdf(r_point: Point, shared: Point, context: bytes) -> bytes:
    return hashlib.sha256(b"busca-total-kem-v1" + p256.encode(r_point) + p256.encode(shared) + context).digest()


def deal(threshold: int, n_members: int) -> tuple[PublicKey, list[KeyShare]]:
    """
    Trusted-dealer key generation: draws x, hands out the shares and forgets x.
    (A deployment would run a DKG so that x never exists anywhere, not even here.)
    """
    if not 1 <= threshold <= n_members:
        raise ValueError("need 1 <= threshold <= n_members")
    coefficients = [_random_scalar() for _ in range(threshold)]  # f(z) = x + a1 z + ... ; x = coefficients[0]
    shares = []
    for index in range(1, n_members + 1):
        value = 0
        for coefficient in reversed(coefficients):  # Horner
            value = (value * index + coefficient) % ORDER
        shares.append(KeyShare(index=index, value=value))
    public = PublicKey(
        point=p256.multiply(coefficients[0], G),
        threshold=threshold,
        verification_points={share.index: p256.multiply(share.value, G) for share in shares},
    )
    return public, shares


def encapsulate(public: PublicKey, context: bytes) -> tuple[Point, bytes]:
    """Returns (R, key). Only R is stored; `key` encrypts the payload and is then dropped."""
    r = _random_scalar()
    r_point = p256.multiply(r, G)
    return r_point, _kdf(r_point, p256.multiply(r, public.point), context)


def partial_decrypt(share: KeyShare, r_point: Point) -> PartialDecryption:
    if r_point is None or not p256.is_on_curve(r_point):
        raise ValueError("invalid ciphertext point")
    return PartialDecryption(index=share.index, point=p256.multiply(share.value, r_point))


def _challenge(r_point: Point, verification: Point, partial: Point, a1: Point, a2: Point) -> int:
    data = b"".join(p256.encode(point) for point in (G, r_point, verification, partial, a1, a2))
    return int.from_bytes(hashlib.sha256(b"busca-total-dleq-v1" + data).digest(), "big") % ORDER


def prove_partial(share: KeyShare, r_point: Point, partial: PartialDecryption) -> ShareProof:
    """Chaum-Pedersen proof (Fiat-Shamir) that `partial` was computed with the member's real share."""
    w = _random_scalar()
    challenge = _challenge(
        r_point, p256.multiply(share.value, G), partial.point, p256.multiply(w, G), p256.multiply(w, r_point)
    )
    return ShareProof(challenge=challenge, response=(w + challenge * share.value) % ORDER)


def verify_partial(public: PublicKey, r_point: Point, partial: PartialDecryption, proof: ShareProof) -> bool:
    verification = public.verification_points.get(partial.index)
    if verification is None or partial.point is None or not p256.is_on_curve(partial.point):
        return False
    minus_c = ORDER - proof.challenge
    a1 = p256.add(p256.multiply(proof.response, G), p256.multiply(minus_c, verification))
    a2 = p256.add(p256.multiply(proof.response, r_point), p256.multiply(minus_c, partial.point))
    if a1 is None or a2 is None:
        return False
    return proof.challenge == _challenge(r_point, verification, partial.point, a1, a2)


def combine(public: PublicKey, r_point: Point, partials: list[PartialDecryption], context: bytes) -> bytes:
    """
    Recovers the encapsulated key from `threshold` partial decryptions. With fewer
    partials (or a wrong one) the result is just a different, useless key: the caller
    notices when the AES-GCM tag of the payload does not verify.
    """
    by_index = {partial.index: partial for partial in partials}
    if len(by_index) < public.threshold:
        raise ValueError(f"need {public.threshold} distinct partial decryptions, got {len(by_index)}")
    chosen = sorted(by_index)[: public.threshold]
    shared = None
    for index in chosen:
        shared = p256.add(shared, p256.multiply(_lagrange_at_zero(index, chosen), by_index[index].point))
    if shared is None:
        raise ValueError("partial decryptions combine to the identity")
    return _kdf(r_point, shared, context)


# -- baseline: plain Shamir reconstruction (what threshold decryption avoids) ----------

def reconstruct_secret(shares: list[KeyShare]) -> int:
    """
    Rebuilds x from t shares. Kept only to measure/contrast: whoever runs this holds
    the whole key from then on and can open every ciphertext of the period alone.
    """
    indexes = [share.index for share in shares]
    if len(set(indexes)) != len(indexes):
        raise ValueError("duplicate shares")
    return sum(share.value * _lagrange_at_zero(share.index, indexes) for share in shares) % ORDER


def decapsulate(secret: int, r_point: Point, context: bytes) -> bytes:
    if r_point is None or not p256.is_on_curve(r_point):
        raise ValueError("invalid ciphertext point")
    return _kdf(r_point, p256.multiply(secret, r_point), context)
